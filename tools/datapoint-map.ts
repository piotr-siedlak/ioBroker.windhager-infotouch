/** Generates docs/DATAPOINTS_MB6621.md from the real-device fixture using the adapter's own discovery code. */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { InfoWinRestApi } from '../src/api/InfoWinRestApi';
import { displayCode } from '../src/api/parsers';
import { loadTextTables } from '../src/api/ResourceTexts';
import { isWritableByController } from '../src/discovery/CapabilityRegistry';
import { scanSystem } from '../src/discovery/SystemScanner';
import { applyLabels } from '../src/mappings/Naming';
import { shapeFor } from '../src/mappings/StateRoles';
import { StateRegistry } from '../src/services/StateRegistry';
import { FakeController, type Fixture } from '../test/helpers/FakeController';
import { makeClient } from '../test/helpers/util';

void (async () => {
    const fixture = JSON.parse(
        readFileSync(join(__dirname, '..', 'test', 'fixtures', 'mb6621-real.json'), 'utf8'),
    ) as Fixture;
    const fake = new FakeController(fixture);
    await fake.start();
    const c = makeClient(fake);
    const cat = await scanSystem(new InfoWinRestApi(c), { excludedNodes: new Set(), includeLon: false });
    applyLabels(cat, await loadTextTables(c, 'en'));
    c.close();
    await fake.stop();
    const lines = [
        '# Datapoints of the reference installation (MB6621, firmware 0.10.4)',
        '',
        'Generated by `tools/datapoint-map.ts` from the sanitised capture `test/fixtures/mb6621-real.json` (read-only probe,',
        "2026-10-22). Names are the controller's own English texts; with another language set they follow that language.",
        'Values are the ones at capture time. **RW** = the controller marks it writable (the adapter still writes nothing',
        'unless you enable writes and allow-list the OID).',
        '',
    ];
    for (const m of cat.modules) {
        for (const f of m.functions.filter(fn => fn.lookups.length > 0 && fn.fctType !== -1)) {
            lines.push(
                `## Node ${m.nodeId} \`${m.label ?? m.name}\` - function ${f.fctId} \`${f.label ?? f.name}\` (type ${f.fctType})`,
                '',
            );
            lines.push(
                '| State id (`windhager-infotouch.0.` + ...) | Name | Value | Unit | Type | RW |',
                '| --- | --- | --- | --- | --- | --- |',
            );
            for (const g of f.lookups) {
                for (const dp of g.datapoints) {
                    const shape = shapeFor(dp, false);
                    const value =
                        dp.typeId === 30
                            ? '(object)'
                            : shape.states && dp.value !== null
                              ? `${dp.value} = ${shape.states[dp.value] ?? '?'}`
                              : (dp.value ?? '-');
                    lines.push(
                        `| \`${StateRegistry.stateId(dp)}\` | ${dp.label ?? displayCode(dp)} | ${value} | ${shape.unit ?? ''} | ${shape.type} | ${isWritableByController(dp) ? 'RW' : ''} |`,
                    );
                }
            }
            lines.push('');
        }
    }
    writeFileSync(join(__dirname, '..', 'docs', 'DATAPOINTS_MB6621.md'), `${lines.join('\n')}\n`);
    console.log('written', lines.length, 'lines');
})();
